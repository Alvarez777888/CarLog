ALTER TABLE records ADD COLUMN IF NOT EXISTS reminder_version BIGINT NOT NULL DEFAULT 1;
CREATE TABLE IF NOT EXISTS reminder_deliveries(
    record_id BIGINT REFERENCES records(id) ON DELETE CASCADE,
    chat_id BIGINT REFERENCES telegram_links(chat_id) ON DELETE CASCADE,
    version BIGINT NOT NULL,
    stage INTEGER NOT NULL,
    PRIMARY KEY(record_id,chat_id,version,stage)
);

ALTER TABLE cars ADD COLUMN IF NOT EXISTS request_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_cars_request ON cars(owner_login,request_key);

CREATE TABLE IF NOT EXISTS account_imports(
login TEXT REFERENCES users(login) ON DELETE CASCADE,
fingerprint TEXT NOT NULL,
PRIMARY KEY(login,fingerprint));
