
CREATE TABLE IF NOT EXISTS users(
    login TEXT PRIMARY KEY,
    salt TEXT NOT NULL,
    password TEXT NOT NULL,
    email TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS cars(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand TEXT NOT NULL,
    model TEXT NOT NULL,
    year INTEGER DEFAULT 0,
    fuel TEXT DEFAULT '',
    engine DOUBLE PRECISION DEFAULT 0,
    mileage INTEGER DEFAULT 0,
    owner_login TEXT NOT NULL REFERENCES users(login) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS categories(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS records(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car BIGINT NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    day TEXT NOT NULL,
    category TEXT DEFAULT '',
    description TEXT DEFAULT '',
    amount DOUBLE PRECISION DEFAULT 0,
    mileage INTEGER DEFAULT 0,
    liters DOUBLE PRECISION DEFAULT 0,
    price DOUBLE PRECISION DEFAULT 0,
    place TEXT DEFAULT '',
    comment TEXT DEFAULT '',
    next_day TEXT DEFAULT '',
    done INTEGER DEFAULT 0,
    notified INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS tokens(
    token_hash TEXT PRIMARY KEY,
    login TEXT NOT NULL REFERENCES users(login) ON DELETE CASCADE,
    expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS telegram_links(
    chat_id BIGINT PRIMARY KEY,
    login TEXT NOT NULL REFERENCES users(login) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS link_codes(
    code TEXT PRIMARY KEY,
    login TEXT NOT NULL REFERENCES users(login) ON DELETE CASCADE,
    expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS recovery_codes(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login TEXT NOT NULL REFERENCES users(login) ON DELETE CASCADE,
    method TEXT NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    used INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS outbox(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    text TEXT NOT NULL,
    sent INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_records_car ON records(car);
CREATE INDEX IF NOT EXISTS idx_records_kind ON records(kind);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users(lower(email)) WHERE email<>'';
ALTER TABLE records ADD COLUMN IF NOT EXISTS source_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_records_source ON records(car,source_key);
CREATE TABLE IF NOT EXISTS login_attempts(login TEXT NOT NULL, attempted_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS idx_login_attempts_time ON login_attempts(attempted_at);
CREATE TABLE IF NOT EXISTS link_attempts(chat_id BIGINT NOT NULL, attempted_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS idx_link_attempts_time ON link_attempts(attempted_at);
